using System.Diagnostics.CodeAnalysis;

namespace ElPaqueto.Security.Data;

/// <summary>
/// An API key of a user. The secret part of the token is never stored: only its SHA-256 hash.
/// </summary>
/// <remarks>
/// Use <c>IApiKeyService</c> to create, validate and revoke keys; it never returns this entity, so
/// the hash does not leave the security module.
/// </remarks>
public class ApiKey
{
    /// <summary>Maximum length of <see cref="Name"/>.</summary>
    public const int MaxNameLength = 100;

    /// <summary>Length of <see cref="SecretHash"/>, in bytes (SHA-256).</summary>
    public const int SecretHashLength = 32;

    /// <summary>The identifier, generated by the application.</summary>
    public Guid Id { get; set; }

    /// <summary>The public key identifier, part of the token. Unique.</summary>
    public string KeyId { get; set; } = string.Empty;

    /// <summary>SHA-256 of the secret part of the token. Never exposed.</summary>
    [SuppressMessage("Performance", "CA1819:Properties should not return arrays", Justification = "Entity property mapped by EF Core to a BLOB column.")]
    public byte[] SecretHash { get; set; } = [];

    /// <summary>The user who owns the key.</summary>
    public Guid OwnerUserId { get; set; }

    /// <summary>The owner. Loaded on demand.</summary>
    public User? Owner { get; set; }

    /// <summary>A label chosen by the owner, for example <c>ci-main</c>.</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// The permissions requested for the key. At use they are intersected with the owner's current
    /// permissions.
    /// </summary>
    public Permission Permissions { get; set; }

    /// <summary>When the key was created (UTC).</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>When the key stops being valid (UTC), or <see langword="null"/> if it never expires.</summary>
    public DateTime? ExpiresAt { get; set; }

    /// <summary>When the key was revoked (UTC), or <see langword="null"/> if it is not revoked.</summary>
    public DateTime? RevokedAt { get; set; }

    /// <summary>
    /// When the key was last used successfully (UTC), recorded with a coarse granularity
    /// (<c>Security:ApiKeys:LastUsedUpdateInterval</c>).
    /// </summary>
    public DateTime? LastUsedAt { get; set; }

    /// <summary>Concurrency token, regenerated on every update made through the change tracker.</summary>
    public string ConcurrencyStamp { get; set; } = Guid.NewGuid().ToString("N");
}
